export const REDFISH_POLL_PY = j([
  '#!/usr/bin/env python3',
  '"""Poll a BMC over Redfish (DMTF ThermalMetrics / PowerSupplyMetrics schemas) every 10 s, one JSON line per sample."""',
  'import json',
  'import sys',
  'import time',
  '',
  '',
  'def get(session, base, path):',
  '    r = session.get(base + path, timeout=10, verify=False)',
  '    r.raise_for_status()',
  '    return r.json()',
  '',
  '',
  'def reading(obj, key):',
  '    val = (obj or {}).get(key) or {}',
  '    return val.get("Reading") if isinstance(val, dict) else val',
  '',
  '',
  'def poll(bmc, user, password, out, period=10.0):',
  '    import requests  # imported lazily so the kit syntax-checks without it',
  '',
  '    requests.packages.urllib3.disable_warnings()',
  '    s = requests.Session()',
  '    s.auth = (user, password)',
  '    base = "https://%s" % bmc',
  '    chassis = [m["@odata.id"] for m in get(s, base, "/redfish/v1/Chassis")["Members"]]',
  '    while True:',
  '        rec = {"t": time.time(), "bmc": bmc, "chassis": {}}',
  '        for c in chassis:',
  '            d = {}',
  '            try:',
  '                tm = get(s, base, c + "/ThermalSubsystem/ThermalMetrics")',
  '                summary = tm.get("TemperatureSummaryCelsius") or {}',
  '                d["intakeC"] = reading(summary, "Intake")',
  '                d["exhaustC"] = reading(summary, "Exhaust")',
  '            except requests.HTTPError:',
  '                pass',
  '            try:',
  '                psus = get(s, base, c + "/PowerSubsystem/PowerSupplies")["Members"]',
  '                d["psuInputW"] = [reading(get(s, base, p["@odata.id"] + "/Metrics"), "InputPowerWatts") for p in psus]',
  '                d["psuCapacityW"] = [get(s, base, p["@odata.id"]).get("PowerCapacityWatts") for p in psus]',
  '            except requests.HTTPError:',
  '                pass',
  '            rec["chassis"][c] = d',
  '        out.write(json.dumps(rec) + "\\n")',
  '        out.flush()',
  '        time.sleep(period)',
  '',
  '',
  'if __name__ == "__main__":',
  '    poll(sys.argv[1], sys.argv[2], sys.argv[3], sys.stdout)',
]);

export const TEST_THERMAL_PY = j([
  '"""60-thermal-power: inlet envelope and PSU capacity from the Redfish time series."""',
  'import json',
  '',
  'import pytest',
  '',
  '',
  'def _samples(logs):',
  '    base = logs / "thermal-power"',
  '    if not base.exists():',
  '        pytest.skip("run 60-thermal-power/redfish_poll.sh during stages 30 and 40")',
  '    for f in sorted(base.glob("*.jsonl")):',
  '        for line in f.read_text(encoding="utf-8", errors="replace").splitlines():',
  '            try:',
  '                yield json.loads(line)',
  '            except ValueError:',
  '                continue',
  '',
  '',
  'def test_inlet_envelope(logs, threshold, results):',
  '    t = threshold("thermal.inlet-air")',
  '    temps = [c.get("intakeC") for s in _samples(logs) for c in s["chassis"].values() if c.get("intakeC") is not None]',
  '    if not temps:',
  '        pytest.skip("no intake readings")',
  '    worst = max(temps)',
  '    results.stage("60-thermal-power")["maxInletC"] = worst',
  '    ok = t["value"] <= min(temps) and worst <= t["max"]',
  '    results.check(t["id"], worst, ok)',
  '    assert ok',
  '',
  '',
  'def test_psu_capacity(logs, threshold, results):',
  '    t = threshold("power.psu-capacity")',
  '    worst = 0.0',
  '    for s in _samples(logs):',
  '        for c in s["chassis"].values():',
  '            for w, cap in zip(c.get("psuInputW") or [], c.get("psuCapacityW") or []):',
  '                if w is not None and cap:',
  '                    worst = max(worst, w / cap)',
  '    results.check(t["id"], worst, worst <= t["value"])',
  '    assert worst <= t["value"]',
]);

