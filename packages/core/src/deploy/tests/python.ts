  '    out["etaFabric"] = out["runs"]["cross-spine"]["etaBus"] / out["runs"]["single-leaf"]["etaBus"]',
  '    text = json.dumps(out, indent=2)',
  '    print(text)',
  '    if args.out:',
  '        pathlib.Path(args.out).write_text(text, encoding="utf-8")',
  '    return 0',
  '',
  '',
  'if __name__ == "__main__":',
  '    sys.exit(main())',
