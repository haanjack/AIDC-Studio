export const PARSERS_PY = j([
  '"""Log parsers: nccl-tests / rccl-tests stdout, perftest ib_write_bw, η calibration."""',
  'import json',
  'import re',
  'from statistics import median',
  '',
  '_LABEL = re.compile(r"^\\s*\\d+:\\s")',
  '_AVG = re.compile(r"#\\s*Avg bus bandwidth\\s*:\\s*([0-9.eE+-]+)\\s*(OK|FAILED)?")',
  '_ROW = re.compile(r"^\\s*(\\d+)\\s+(\\d+)\\s+(\\S+)\\s+(\\S+)\\s+(-?\\d+)\\s+(.*)$")',
  '_COLL = re.compile(r"#\\s*Collective test starting:\\s*(\\w+)")',
  '',
  '',
  'def _num(tok):',
  '    try:',
  '        return float(tok)',
  '    except (TypeError, ValueError):',
  '        return None',
  '',
  '',
  'def parse_nccl_text(text):',
  '    """nccl-tests / rccl-tests stdout -> rows (size, count, type, redop, root, out_of_place, in_place) + footer average."""',
  '    rows, avg, verdict, collective = [], None, None, None',
  '    for raw in text.splitlines():',
  '        line = _LABEL.sub("", raw)',
  '        m = _COLL.search(line)',
  '        if m:',
  '            collective = m.group(1)',
  '            continue',
  '        m = _AVG.search(line)',
  '        if m:',
  '            avg, verdict = float(m.group(1)), m.group(2)',
  '            continue',
  '        if line.lstrip().startswith("#"):',
  '            continue',
  '        m = _ROW.match(line)',
  '        if not m:',
  '            continue',
  '        size, count, dtype, redop, root, rest = m.groups()',
  '        f = rest.split()',
  '        if len(f) >= 8:',
  '            oop = dict(time=_num(f[0]), algbw=_num(f[1]), busbw=_num(f[2]), nwrong=_num(f[3]))',
  '            ip_ = dict(time=_num(f[4]), algbw=_num(f[5]), busbw=_num(f[6]), nwrong=_num(f[7]))',
  '        elif len(f) >= 4:',
  '            oop = None',
  '            ip_ = dict(time=_num(f[0]), algbw=_num(f[1]), busbw=_num(f[2]), nwrong=_num(f[3]))',
  '        else:',
  '            continue',
  '        rows.append(dict(size=int(size), count=int(count), type=dtype, redop=redop, root=int(root), out_of_place=oop, in_place=ip_))',
  '    return dict(rows=rows, avg_busbw=avg, verdict=verdict, collective=collective)',
  '',
  '',
  'def _busbw(row):',
  '    """out-of-place busbw (in-place is the cross-check)."""',
  '    for key in ("out_of_place", "in_place"):',
  '        part = row.get(key) or {}',
  '        if part.get("busbw") is not None:',
  '            return part["busbw"]',
  '    return None',
  '',
  '',
  'def plateau_busbw(rows, min_bytes=1 << 30):',
  '    """mean busbw over the three largest sizes >= 1 GiB (fewer -> what exists, flagged below plateau)."""',
  '    big = sorted((r for r in rows if r["size"] >= min_bytes and _busbw(r) is not None), key=lambda r: r["size"])[-3:]',
  '    flags = []',
  '    if not big:',
  '        big = sorted((r for r in rows if _busbw(r) is not None), key=lambda r: r["size"])[-3:]',
  '        flags.append("below-plateau")',
  '    if not big:',
  '        return None, ["no-rows"]',
  '    vals = [_busbw(r) for r in big]',
  '    if max(vals) > 0 and (max(vals) - min(vals)) / max(vals) > 0.10:',
  '        flags.append("not-plateaued")',
  '    # same flags as the Network panel parser (engines/eta.ts): unstable = a size >= 256 MiB drops > 15 % below its predecessor;',
  '    # in-place-differs = in-place busbw differs from out-of-place by > 3 %',
  '    seq = sorted((r for r in rows if _busbw(r) is not None), key=lambda r: r["size"])',
  '    for prev, cur in zip(seq, seq[1:]):',
  '        if cur["size"] >= 256 << 20 and _busbw(prev) > 0 and _busbw(cur) < 0.85 * _busbw(prev):',
  '            flags.append("unstable")',
  '            break',
  '    for r in seq:',
  '        oop = (r.get("out_of_place") or {}).get("busbw")',
  '        ip_ = (r.get("in_place") or {}).get("busbw")',
  '        if oop and ip_ is not None and abs(ip_ - oop) / oop > 0.03:',
  '            flags.append("in-place-differs")',
  '            break',
  '    return sum(vals) / len(vals), flags',
  '',
  '',
  'def eta_bus(plateau_gbps, nic_gbps, nics_per_rank=1):',
  '    """η_bus = plateau busbw / (NIC Gb/s / 8), decimal GB/s as nccl-tests (1.0E9)."""',
  '    return plateau_gbps / (nic_gbps * nics_per_rank / 8.0)',
  '',
  '',
  'def has_errors(parsed):',
  '    if parsed.get("verdict") == "FAILED":',
  '        return True',
  '    for r in parsed["rows"]:',
  '        for key in ("out_of_place", "in_place"):',
  '            part = r.get(key) or {}',
  '            if part.get("nwrong") not in (None, 0.0):',
  '                return True',
  '    return False',
  '',
  '',
  'def parse_perftest(text):',
  '    """ib_write_bw report: data line with the message size -> BW average Gb/s (field 3), as the Azure health checks parse it."""',
  '    for line in text.splitlines():',
  '        f = line.split()',
  '        if len(f) >= 4 and f[0].isdigit() and f[1].isdigit():',
  '            return _num(f[3])',
  '    return None',
  '',
  '',
  'def load_json(path):',
  '    with open(path, encoding="utf-8") as fh:',
  '        return json.load(fh)',
  '',
  '',
  'def median_or_none(vals):',
  '    vals = [v for v in vals if v is not None]',
  '    return median(vals) if vals else None',
]);

